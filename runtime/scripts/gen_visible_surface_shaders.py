"""Compile and validate both shaders for the experimental NVN scene reflection pass."""
from pathlib import Path
import tempfile
from gen_taau_shaders import compile_one, find_glslang, find_spirv_val

if __name__ == "__main__":
    extras = Path(__file__).resolve().parents[1] / "src/gfx/extras"
    compiler, validator = find_glslang(), find_spirv_val()
    if not validator:
        raise SystemExit("spirv-val is required for the ray-query shaders")
    lines = ["// Generated by runtime/scripts/gen_visible_surface_shaders.py", ""]
    with tempfile.TemporaryDirectory() as temp:
        for shader, symbol in [("visible_surface_mesh", "kMesh"), ("visible_surface_reflections", "kReflect")]:
            words = compile_one(compiler, validator, temp, shader, (extras / "shaders" / (shader + ".comp")).read_text())
            lines.append(f"static constexpr uint32_t {symbol}[] = {{")
            for start in range(0, len(words), 8):
                lines.append("    " + ", ".join(f"0x{v:08x}" for v in words[start:start+8]) + ",")
            lines.append("};")
    (extras / "visible_surface_shaders.inc").write_text("\n".join(lines) + "\n", newline="\n")
